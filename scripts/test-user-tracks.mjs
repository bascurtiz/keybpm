import fs from 'node:fs';
import path from 'node:path';
import decode from 'audio-decode';
import { analyzeBeatGrid } from '../src/lib/dj/beatgrid.ts';

function toAudioBuffer(decoded) {
  const channels = decoded.channelData;
  const sampleRate = decoded.sampleRate;
  const length = channels[0].length;
  const duration = length / sampleRate;
  const numberOfChannels = channels.length;
  return {
    sampleRate,
    length,
    duration,
    numberOfChannels,
    getChannelData(c) { return channels[c]; },
    copyFromChannel(dest, c, start = 0) {
      const src = channels[c];
      const copyLen = Math.min(dest.length, Math.max(0, src.length - start));
      for (let i = 0; i < copyLen; i++) {
        dest[i] = src[start + i];
      }
    }
  };
}

const files = [
  'D:/Music/keybpm-test/Fish Go Deep, Tracey K, Dennis Ferrer - The Cure & The Cause (Dennis Ferrer Remix).mp3',
  'D:/Music/keybpm-test/Nightcrawlers - Push The Feeling On (Mk Dub Revisited Edit).flac'
];

async function main() {
  for (const file of files) {
    console.log('\n======================================================');
    console.log('Testing file:', path.basename(file));
    const buf = fs.readFileSync(file);
    const rawAudio = await decode(buf);
    const audio = toAudioBuffer(rawAudio);
    const sr = audio.sampleRate;
    const ch0 = audio.getChannelData(0);

    let firstSound = 0;
    for (let i = 0; i < sr * 10; i++) {
      if (Math.abs(ch0[i]) > 0.01) {
        firstSound = i / sr;
        break;
      }
    }
    console.log(`First sound onset: ${firstSound.toFixed(4)}s (${(firstSound * 1000).toFixed(1)}ms)`);

    const result = await analyzeBeatGrid(audio);
    console.log('Detection result:', result);
    if (result) {
      const beatLen = 60 / result.bpm;
      console.log(`BPM: ${result.bpm.toFixed(2)} (beatLen = ${(beatLen * 1000).toFixed(2)}ms)`);
      console.log(`firstBeat: ${result.firstBeat.toFixed(4)}s (${(result.firstBeat * 1000).toFixed(1)}ms)`);
      console.log(`firstBar: ${result.firstBar.toFixed(4)}s (${(result.firstBar * 1000).toFixed(1)}ms)`);

      // Print first 8 beats generated by grid
      console.log('First 8 grid beats:');
      for (let k = 0; k < 8; k++) {
        const t = result.firstBar + k * beatLen;
        const beatsFromBar = Math.round((t - result.firstBar) / beatLen);
        const isDownbeat = ((beatsFromBar % result.beatsPerBar) + result.beatsPerBar) % result.beatsPerBar === 0;
        console.log(`  Beat ${k + 1}: t = ${t.toFixed(4)}s [${isDownbeat ? 'DOWNBEAT (BAR 1)' : 'beat'}]`);
      }
    }
  }
}

main().catch(console.error);
